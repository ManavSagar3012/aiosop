"""Execution-time admission and provider testimony for approved replay steps.

The graph is a bounded source inventory, not permission to navigate.  The only
authority for a replay child is its running, human-approved PostgreSQL TaskORM
bound to the original signed source task, Flow and ROE.  Provider testimony
does not establish independent target-side authorization failure.
"""

import re
from typing import Any, Dict, Optional

from ai_osop.core.exceptions import WorkflowException
from ai_osop.core.models import Task
from ai_osop.memory.session_memory import SessionMemory
from ai_osop.safety.scope import ScopeEnforcer, validate_payload_targets


_LABEL = re.compile(r"[A-Za-z0-9_.-]{1,64}\Z")
_STEP = re.compile(r"step-[A-Za-z0-9._-]{1,80}\Z")
_WORKFLOW = re.compile(r"wf-[A-Za-z0-9._-]{1,80}\Z")


async def authorize_replay_step(ctx: Any, payload: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    """Return the immutable permitted replay step, or None for manual navigation.

    All checked facts are read from the original PostgreSQL records.  A failed
    lookup or a mismatched Neo4j projection denies *before* any browser action.
    """
    task = getattr(ctx, "current_task", None)
    if not isinstance(task, Task) or task.type != "navigate":
        return None
    if not isinstance(task.payload, dict):
        raise WorkflowException("Replay task payload unavailable")
    signed = type(task.payload.get("_authorization_version")) is int
    if not signed:
        return None  # Unrelated manual navigation retains existing behavior.
    if not any(
        marker in task.payload for marker in ("source_user_label", "step_id", "workflow_id")
    ):
        # An unrelated signed/manual GET navigation is not a differential
        # replay. Its own ordinary ROE/approval gates remain authoritative;
        # don't impose a non-existent replay parent or graph step on it.
        return None
    if not isinstance(ctx.session_memory, SessionMemory):
        raise WorkflowException("Signed replay requires PostgreSQL authority")
    expected = task.payload
    version = expected.get("_authorization_version")
    flow_revision = expected.get("_flow_revision")
    step_id = expected.get("step_id")
    workflow_id = expected.get("workflow_id")
    source_label = expected.get("source_user_label")
    target_label = expected.get("user_label")
    comparison_role = expected.get("_comparison_role", "target")
    if (
        type(version) is not int
        or version < 1
        or type(flow_revision) is not int
        or flow_revision < 0
        or not isinstance(step_id, str)
        or not _STEP.fullmatch(step_id)
        or not isinstance(workflow_id, str)
        or not _WORKFLOW.fullmatch(workflow_id)
        or not isinstance(source_label, str)
        or not _LABEL.fullmatch(source_label)
        or not isinstance(target_label, str)
        or not _LABEL.fullmatch(target_label)
        or comparison_role not in {"source", "target"}
        or (comparison_role == "target" and source_label == target_label)
        or (comparison_role == "source" and source_label != target_label)
        or expected.get("method") != "GET"
        or not task.flow_id
        or not task.parent_task_id
        or task.engagement_id != ctx.session_id
        or task.dependencies != [task.parent_task_id]
        or not task.approval_required
        or task.max_retries != 0
    ):
        raise WorkflowException("Signed replay step has invalid immutable lineage")
    # These runtime aliases are generated by BaseAgent on a private copy;
    # they must never change the persisted, signed original step payload.
    for field in ("url", "user_label", "step_id", "workflow_id", "method"):
        if payload.get(field) != expected.get(field):
            raise WorkflowException("Signed replay execution payload was substituted")

    memory = ctx.session_memory
    try:
        current = await memory.load_task_authoritative(task.id)
        parent = await memory.load_task_authoritative(task.parent_task_id)
        source = await memory.load_task_authoritative(parent.parent_task_id) if parent else None
        flow = await memory.load_flow(task.flow_id)
        engagement = await memory.load_session_state(task.engagement_id)
        approval = expected.get("approval_id")
        parent_approval = (
            parent.payload.get("approval_id")
            if parent and isinstance(parent.payload, dict)
            else None
        )
        if (
            not isinstance(current, Task)
            or current.id != task.id
            or current.status != "running"
            or current.payload != expected
            or current.engagement_id != task.engagement_id
            or current.flow_id != task.flow_id
            or current.parent_task_id != task.parent_task_id
            or current.type != "navigate"
            or current.dependencies != [task.parent_task_id]
        ):
            raise WorkflowException("Signed replay worker claim is stale")
        if (
            not isinstance(parent, Task)
            or parent.type != "replay_for_diff_auth"
            or parent.engagement_id != task.engagement_id
            or parent.flow_id != task.flow_id
            or parent.status != "completed"
            or not parent.approval_required
            or not isinstance(parent.payload, dict)
            or parent.payload.get("_authorization_version") != version
            or parent.payload.get("_flow_revision") != flow_revision
            or parent.payload.get("workflow_id") != workflow_id
            or parent.payload.get("source_user_label") != source_label
            or not isinstance(parent.payload.get("target_user_label"), str)
            or parent.payload["target_user_label"] == source_label
            or (
                comparison_role == "target"
                and parent.payload.get("target_user_label") != target_label
            )
            or (
                comparison_role == "source"
                and parent.payload.get("target_user_label") != expected.get("target_user_label")
            )
            or parent.payload.get("operator_approved") is not True
            or not isinstance(parent_approval, str)
            or not await memory.is_task_approved(parent.id, task.engagement_id, parent_approval)
            or not isinstance(source, Task)
            or source.id != parent.parent_task_id
            or source.type != "map_workflow"
            or source.status != "completed"
            or source.engagement_id != task.engagement_id
            or source.flow_id not in {None, task.flow_id}
            or not isinstance(source.payload, dict)
            or source.payload.get("_authorization_version") != version
            or source.payload.get("user_label") != source_label
            or not isinstance(source.result, dict)
            or source.result.get("workflow_id") != workflow_id
            or source.result.get("status") not in {"success", "workflow_recorded"}
            or flow is None
            or flow.engagement_id != task.engagement_id
            or flow.status not in {"pending", "running"}
            or flow.revision != flow_revision
            or engagement is None
            or engagement.phase in {"halted", "completed"}
            or engagement.scope.engagement_id != task.engagement_id
            or not current.approval_required
            or expected.get("operator_approved") is not True
            or not isinstance(approval, str)
            or not await memory.is_task_approved(task.id, task.engagement_id, approval)
        ):
            raise WorkflowException("Replay source, Flow or distinct approvals not current")
        enforcer = ScopeEnforcer(engagement.scope)
        enforcer.validate_time_window()
        await memory.assert_signed_authorization(task.engagement_id, expected_version=version)
        validate_payload_targets(enforcer, {"url": expected.get("url")}, require_target=True)
        validate_payload_targets(enforcer, {"url": source.payload.get("url")}, require_target=True)
        # Exact tenant-joined Step->Endpoint binding from the original source
        # workflow; its method and URL must match the already admitted Task.
        cypher = (
            "MATCH (w:Workflow {id:$wid, engagement_id:$eid})-[:HAS_STEP]->"
            "(s:Step {id:$sid, engagement_id:$eid, workflow_id:$wid})"
            "-[:TARGETS_ENDPOINT]->(e:Endpoint {engagement_id:$eid}) "
            "WHERE s.endpoint_id=e.id "
            "RETURN w.role AS role, e.url AS url, e.method AS method, "
            "s.action_type AS action LIMIT 2"
        )
        async with ctx.graph_memory._driver.session() as graph:
            records = await graph.run(
                cypher, {"wid": workflow_id, "eid": task.engagement_id, "sid": step_id}
            )
            rows = [dict(row) async for row in records]
        if (
            len(rows) != 1
            or rows[0].get("role") != source_label
            or rows[0].get("url") != expected.get("url")
            or rows[0].get("method") != "GET"
            or rows[0].get("action") not in {"NAVIGATE", "GET"}
        ):
            raise WorkflowException("Replay step graph/source binding changed")
        # A fresh signed check follows all awaited graph/approval lookups.
        await memory.assert_signed_authorization(task.engagement_id, expected_version=version)
        fresh = await memory.load_task_authoritative(task.id)
        if not isinstance(fresh, Task) or fresh.status != "running" or fresh.payload != expected:
            raise WorkflowException("Replay execution claim changed before browser dispatch")
        return {
            "version": version,
            "url": expected["url"],
            "user_label": target_label,
            "step_id": step_id,
            "workflow_id": workflow_id,
            "comparison_role": comparison_role,
            "target_user_label": parent.payload["target_user_label"],
            # Preserve the original completed map_workflow TaskORM identity;
            # the immediate parent is only the approved replay proposal.
            "source_task_id": source.id,
            "replay_parent_task_id": parent.id,
            "scope": enforcer,
        }
    except WorkflowException:
        raise
    except Exception as exc:
        raise WorkflowException("Signed replay execution authorization unavailable") from exc


async def signed_replay_provider_evidence(
    ctx: Any, *, version: int, url: str, scope: Any
) -> Optional[Dict[str, Any]]:
    """Read independently persisted *provider testimony*, never target proof."""
    from ai_osop.memory.graph_research_projection import verify_signed_action_event

    task = ctx.current_task
    store = getattr(ctx, "supervision_store", None)
    if store is None:
        return None
    try:
        dispatches = await store.list_mcp_dispatches(ctx.session_id, task_id=task.id, limit=100)
        matches = [
            d
            for d in dispatches
            if d.get("server_id") == "browser-mcp"
            and d.get("tool_name") == "execute"
            and d.get("status") == "confirmed_finished"
            and d.get("authorization_version") == version
        ]
        if len(matches) != 1:
            return None
        events = await store.list_events(ctx.session_id, task_id=task.id, limit=100)
        qualified = [
            e
            for e in events
            if e.get("engagement_id") == ctx.session_id
            and e.get("task_id") == task.id
            and e.get("kind") in {"agent.mcp.execution_finished", "agent.mcp.reconciliation_result"}
            and isinstance(e.get("payload"), dict)
            and e["payload"].get("request_id") == matches[0]["request_id"]
            and e["payload"].get("status") == "confirmed_finished"
            and e["payload"].get("provider_receipt_status") == "succeeded"
        ]
        if len(qualified) != 1:
            return None
        event = qualified[0]
        body = event["payload"]
        if not await verify_signed_action_event(
            supervision=store,
            engagement_id=ctx.session_id,
            task_id=task.id,
            event_id=event["id"],
            provider_receipt_sha256=body["provider_receipt_sha256"],
            authorization_version=version,
        ):
            return None
        scope.validate_time_window()
        validate_payload_targets(scope, {"url": url}, require_target=True)
        await ctx.session_memory.assert_signed_authorization(
            ctx.session_id, expected_version=version
        )
        return {
            "provider_event_id": event["id"],
            "provider_receipt_sha256": body["provider_receipt_sha256"],
            "source_authenticity_verified": False,
            "target_effect_verified": False,
            "finding_verified": False,
        }
    except Exception:
        return None
